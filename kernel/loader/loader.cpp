BinaryFormat loader_detect_format(const uint8_t* data, size_t size) {
    if (elf_probe(data, size)) {
        return BinaryFormat::ELF64;
    }
    if (pe_probe(data, size)) {
        return BinaryFormat::PE32_PLUS;
    }
    return BinaryFormat::UNKNOWN;
}

bool loader_inspect(const uint8_t* data, size_t size, BinaryInfo* out_info) {
    BinaryFormat fmt = loader_detect_format(data, size);
    if (fmt == BinaryFormat::ELF64) {
        return elf_parse(data, size, out_info);
    }
    if (fmt == BinaryFormat::PE32_PLUS) {
        return pe_parse(data, size, out_info);
    }
    return false;
}

void loader_print_info(const BinaryInfo* info) {
    if (!info) return;

    lib::kprint_str("================================================================\r\n");
    lib::kprint_str("                Binary Container Analysis Report                \r\n");
    lib::kprint_str("================================================================\r\n");

    lib::kprint_str("  Container Format: ");
    switch (info->format) {
        case BinaryFormat::ELF64:
            lib::kprint_str("Linux ELF64 (Executable and Linkable Format)\r\n");
            break;
        case BinaryFormat::PE32_PLUS:
            lib::kprint_str("Windows PE32+ (Portable Executable 64-bit)\r\n");
            break;
        default:
            lib::kprint_str("Unknown / Unsupported Format\r\n");
            break;
    }

    lib::kprint_str("  Target CPU Arch : ");
    if (info->arch == BinaryArch::X86_64) {
        lib::kprint_str("x86_64 (AMD64 64-bit Long Mode)\r\n");
    } else {
        lib::kprint_str("Unknown\r\n");
    }

    lib::kprint_str("  Target Subsystem: ");
    switch (info->subsystem) {
        case BinarySubsystem::LINUX_CLI:
            lib::kprint_str("Linux POSIX Console / CLI\r\n");
            break;
        case BinarySubsystem::WINDOWS_CUI:
            lib::kprint_str("Windows Console (CUI / Win32)\r\n");
            break;
        case BinarySubsystem::WINDOWS_GUI:
            lib::kprint_str("Windows Graphical Interface (GUI)\r\n");
            break;
        default:
            lib::kprint_str("Default / Generic Subsystem\r\n");
            break;
    }

    lib::kprint_str("  Image Base      : ");
    lib::kprint_hex(info->image_base);
    lib::kprint_str("\r\n");

    lib::kprint_str("  Entry Point     : ");
    lib::kprint_hex(info->entry_point);
    lib::kprint_str("\r\n");

    lib::kprint_str("  Image Size      : ");
    lib::kprint_udec(info->image_size);
    lib::kprint_str(" bytes (");
    lib::kprint_udec(info->image_size / 1024);
    lib::kprint_str(" KB)\r\n");

    if (info->format == BinaryFormat::PE32_PLUS) {
        lib::kprint_str("  Stack Reserve   : ");
        lib::kprint_udec(info->stack_reserve / 1024);
        lib::kprint_str(" KB\r\n");

        lib::kprint_str("  Import Table RVA: ");
        lib::kprint_hex(info->import_table_rva);
        lib::kprint_str(" (Size: ");
        lib::kprint_udec(info->import_table_size);
        lib::kprint_str(" bytes)\r\n");
    }

    lib::kprint_str("----------------------------------------------------------------\r\n");
    lib::kprint_str("  Segments / Sections Mapping (Total: ");
    lib::kprint_udec(info->segment_count);
    lib::kprint_str(")\r\n");
    lib::kprint_str("  #  Name      Virtual Address    MemSize    FileSize   Perms\r\n");

    for (size_t i = 0; i < info->segment_count; ++i) {
        const BinarySegment* seg = &info->segments[i];

        lib::kprint_str("  ");
        lib::kprint_udec(i);
        lib::kprint_str("  ");

        size_t name_len = lib::strlen(seg->name);
        lib::kprint_str(seg->name);
        for (size_t s = name_len; s < 10; ++s) {
            lib::kprint_char(' ');
        }

        lib::kprint_hex(seg->vaddr);
        lib::kprint_str(" ");

        lib::kprint_udec(seg->mem_size);
        lib::kprint_str(" B     ");

        lib::kprint_udec(seg->file_size);
        lib::kprint_str(" B     ");

        lib::kprint_char((seg->flags & SEG_FLAG_READ) ? 'R' : '-');
        lib::kprint_char((seg->flags & SEG_FLAG_WRITE) ? 'W' : '-');
        lib::kprint_char((seg->flags & SEG_FLAG_EXEC) ? 'X' : '-');
        lib::kprint_str("\r\n");
    }
    lib::kprint_str("================================================================\r\n");
}

